import Foundation
import Supabase

nonisolated enum ImportedRunSchemaCompatibility {
    private static let expandedColumns = [
        "raw_source_identity",
        "dataset_version",
        "matched_segment_ids",
        "edge_observations",
        "match_confidence",
        "match_method",
        "equipment_id_at_activity"
    ]

    /// Retry only when PostgREST/Postgres explicitly says one of the newer
    /// attribution columns is absent. Authentication, RLS, validation, and
    /// connectivity failures must remain real failures rather than being
    /// hidden behind a second request.
    static func shouldRetryLegacy(after error: Error) -> Bool {
        shouldRetryLegacy(message: error.localizedDescription)
    }

    static func shouldRetryLegacy(message: String) -> Bool {
        missingExpandedColumn(message: message) != nil
    }

    static func missingExpandedColumn(message: String) -> String? {
        let text = message.lowercased()
        guard text.contains("schema cache")
            || text.contains("pgrst204")
            || text.contains("does not exist")
            || text.contains("unknown column") else { return nil }
        return expandedColumns.first(where: text.contains)
    }
}

/// Distinguishes evidence-backed trail labels from UI fallbacks. Persisted
/// fallbacks from older builds are intentionally recognized so re-importing
/// the same source can repair the row instead of being blocked as a duplicate.
nonisolated enum ImportedRunNameQuality {
    /// One naming rule for every activity source and match tier. A graph edge
    /// can be a nameless OSM fragment inside a named trail group, so reading
    /// `edge.attributes.trailName` directly is not sufficient even after a
    /// high-confidence topology match. Resolve through `MountainNaming`, use
    /// the bare trail identity because difficulty is stored separately, and
    /// refuse synthetic fallbacks such as "Run".
    static func evidenceBackedTrailName(
        for edge: GraphEdge,
        naming: MountainNaming
    ) -> String? {
        concreteName(naming.edgeLabel(edge, style: .bareName))
            ?? concreteName(edge.attributes.trailName)
    }

    static func concreteName(_ raw: String?) -> String? {
        guard let raw else { return nil }
        let name = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        return isConcrete(name) ? name : nil
    }

    static func isConcrete(_ raw: String?) -> Bool {
        guard let raw else { return false }
        let name = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !name.isEmpty else { return false }
        let normalized = name.lowercased()
        if normalized == "run" || normalized == "imported run" || normalized == "whole day" {
            return false
        }
        // These are generated by Trail.displayName / MountainNaming when the
        // source has no trail identity. They must not count as a resolved name.
        let unnamedPattern = #"^unnamed (green|blue|black|double black|terrain park|unknown) trail(?:\s*·\s*#\d+)?$"#
        if normalized.range(of: unnamedPattern, options: .regularExpression) != nil { return false }
        let fallbackPattern = #"^(green|blue|black|double black|terrain park)?\s*run\s*(·.*)?$"#
        return normalized.range(of: fallbackPattern, options: .regularExpression) == nil
    }

    static func shouldUpgrade(
        existingName: String?,
        existingConfidence: Double?,
        candidateName: String?,
        candidateConfidence: Double
    ) -> Bool {
        guard isConcrete(candidateName) else { return false }
        if !isConcrete(existingName) { return true }
        return candidateConfidence > (existingConfidence ?? 0) + 0.01
    }
}

/// Superset row used when the observation-provenance migrations are present.
/// Optional source fields also allow this one shape to serve backup restores.
nonisolated struct ImportedRunWriteRow: Encodable {
    let profile_id: String
    let resort_id: String?
    let edge_id: String?
    let difficulty: String?
    let speed_ms: Double
    let peak_speed_ms: Double?
    let duration_s: Double
    let vertical_m: Double
    let distance_m: Double
    let max_grade_deg: Double
    let run_at: Date
    let dedup_hash: String
    let source: String?
    let source_file_hash: String?
    let raw_source_identity: String?
    let dataset_version: String?
    let matched_segment_ids: [String]
    let edge_observations: [EdgePaceObservation]
    let match_confidence: Double
    let match_method: String
    let equipment_id_at_activity: UUID?
    let trail_name: String?
    let conditions_fp: String

    var withoutEdgeObservations: some Encodable {
        ObservationCompatibleImportedRunWriteRow(
            profile_id: profile_id,
            resort_id: resort_id,
            edge_id: edge_id,
            difficulty: difficulty,
            speed_ms: speed_ms,
            peak_speed_ms: peak_speed_ms,
            duration_s: duration_s,
            vertical_m: vertical_m,
            distance_m: distance_m,
            max_grade_deg: max_grade_deg,
            run_at: run_at,
            dedup_hash: dedup_hash,
            source: source,
            source_file_hash: source_file_hash,
            raw_source_identity: raw_source_identity,
            dataset_version: dataset_version,
            matched_segment_ids: matched_segment_ids,
            match_confidence: match_confidence,
            match_method: match_method,
            equipment_id_at_activity: equipment_id_at_activity,
            trail_name: trail_name,
            conditions_fp: conditions_fp
        )
    }

    var legacy: some Encodable {
        LegacyImportedRunWriteRow(
            profile_id: profile_id,
            resort_id: resort_id,
            edge_id: RecordedPaceEvidence.legacyEdgeID(edge_id, method: match_method),
            difficulty: difficulty,
            speed_ms: speed_ms,
            peak_speed_ms: peak_speed_ms,
            duration_s: duration_s,
            vertical_m: vertical_m,
            distance_m: distance_m,
            max_grade_deg: max_grade_deg,
            run_at: run_at,
            dedup_hash: dedup_hash,
            source: source,
            source_file_hash: source_file_hash,
            trail_name: trail_name,
            conditions_fp: conditions_fp
        )
    }
}

