extension SupabaseManager {
    /// Inserts exact new identities and returns their dedup hashes. A schema
    /// mismatch gets one deterministic retry with the legacy payload; all
    /// other errors surface unchanged.
    @MainActor
    func upsertImportedRunRows(_ rows: [ImportedRunWriteRow]) async throws -> Set<String> {
        guard !rows.isEmpty else { return [] }

        struct InsertedIdentity: Decodable {
            let dedup_hash: String
        }

        do {
            let inserted: [InsertedIdentity] = try await client
                .from("imported_runs")
                .upsert(
                    rows,
                    onConflict: "profile_id,dedup_hash",
                    ignoreDuplicates: true
                )
                .select("dedup_hash")
                .execute()
                .value
            let insertedHashes = Set(inserted.map(\.dedup_hash))
            return insertedHashes.union(
                await upgradePreviouslyGenericRuns(rows, excluding: insertedHashes)
            )
        } catch {
            guard let missingColumn = ImportedRunSchemaCompatibility.missingExpandedColumn(
                message: error.localizedDescription
            ) else {
                throw error
            }

            if missingColumn == "edge_observations" {
                do {
                    AppLog.importer.debug(
                        "imported_runs edge observations are pending; preserving other attribution fields"
                    )
                    let inserted: [InsertedIdentity] = try await client
                        .from("imported_runs")
                        .upsert(
                            rows.map(\.withoutEdgeObservations),
                            onConflict: "profile_id,dedup_hash",
                            ignoreDuplicates: true
                        )
                        .select("dedup_hash")
                        .execute()
                        .value
                    let insertedHashes = Set(inserted.map(\.dedup_hash))
                    return insertedHashes.union(
                        await upgradePreviouslyGenericRuns(rows, excluding: insertedHashes)
                    )
                } catch {
                    guard ImportedRunSchemaCompatibility.shouldRetryLegacy(after: error) else {
                        throw error
                    }
                }
            }

            AppLog.importer.debug(
                "imported_runs attribution schema is pending; retrying compatible payload"
            )
            let inserted: [InsertedIdentity] = try await client
                .from("imported_runs")
                .upsert(
                    rows.map(\.legacy),
                    onConflict: "profile_id,dedup_hash",
                    ignoreDuplicates: true
                )
                .select("dedup_hash")
                .execute()
                .value
            let insertedHashes = Set(inserted.map(\.dedup_hash))
            return insertedHashes.union(
                await upgradePreviouslyGenericRuns(rows, excluding: insertedHashes)
            )
        }
    }

    /// Exact re-imports remain idempotent, but a row written before its graph
    /// was available may be upgraded when reconstruction now provides a real
    /// trail and stronger match. This never creates a second run and never
    /// replaces a concrete label with another equally weak guess.
    @MainActor
    private func upgradePreviouslyGenericRuns(
        _ rows: [ImportedRunWriteRow],
        excluding insertedHashes: Set<String>
    ) async -> Set<String> {
        let candidates = rows.filter {
            !insertedHashes.contains($0.dedup_hash)
                && ImportedRunNameQuality.isConcrete($0.trail_name)
        }
        guard !candidates.isEmpty else { return [] }

        struct ExistingRow: Decodable {
            let dedup_hash: String
            let trail_name: String?
            let match_confidence: Double?
        }
        let existing: [ExistingRow]
        do {
            existing = try await client.from("imported_runs")
                .select("dedup_hash,trail_name,match_confidence")
                .eq("profile_id", value: candidates[0].profile_id)
                .in("dedup_hash", values: candidates.map(\.dedup_hash))
                .execute()
                .value
        } catch {
            guard ImportedRunSchemaCompatibility.shouldRetryLegacy(after: error) else {
                AppLog.importer.debug("duplicate-name audit skipped: \(error.localizedDescription)")
                return []
            }
            struct CoreExistingRow: Decodable {
                let dedup_hash: String
                let trail_name: String?
            }
            do {
                let core: [CoreExistingRow] = try await client.from("imported_runs")
                    .select("dedup_hash,trail_name")
                    .eq("profile_id", value: candidates[0].profile_id)
                    .in("dedup_hash", values: candidates.map(\.dedup_hash))
                    .execute()
                    .value
                // Legacy rows have no confidence evidence. Protect an already
                // concrete name from replacement while still allowing a
                // generic/null name to be repaired.
                existing = core.map {
                    ExistingRow(
                        dedup_hash: $0.dedup_hash,
                        trail_name: $0.trail_name,
                        match_confidence: ImportedRunNameQuality.isConcrete($0.trail_name)
                            ? 1
                            : nil
                    )
                }
            } catch {
                AppLog.importer.debug("legacy duplicate-name audit skipped: \(error.localizedDescription)")
                return []
            }
        }
        let existingByHash = Dictionary(
            existing.map { ($0.dedup_hash, $0) },
            uniquingKeysWith: { first, _ in first }
        )

        struct UpgradePayload: Encodable {
            let resort_id: String?
            let edge_id: String?
            let difficulty: String?
            let dataset_version: String?
            let matched_segment_ids: [String]
            let match_confidence: Double
            let match_method: String
            let equipment_id_at_activity: UUID?
            let raw_source_identity: String?
            let trail_name: String?
        }
        struct CoreUpgradePayload: Encodable {
            let resort_id: String?
            let edge_id: String?
            let difficulty: String?
            let trail_name: String?

            enum CodingKeys: String, CodingKey {
                case resort_id, edge_id, difficulty, trail_name
            }

            func encode(to encoder: Encoder) throws {
                var values = encoder.container(keyedBy: CodingKeys.self)
                try values.encodeIfPresent(resort_id, forKey: .resort_id)
                // Explicit null clears a prior learning key when an exact
                // generic-name repair now has only route evidence.
                try values.encode(edge_id, forKey: .edge_id)
                try values.encodeIfPresent(difficulty, forKey: .difficulty)
                try values.encodeIfPresent(trail_name, forKey: .trail_name)
            }
        }

        var upgraded: Set<String> = []
        for candidate in candidates {
            guard let prior = existingByHash[candidate.dedup_hash],
                  ImportedRunNameQuality.shouldUpgrade(
                    existingName: prior.trail_name,
                    existingConfidence: prior.match_confidence,
                    candidateName: candidate.trail_name,
                    candidateConfidence: candidate.match_confidence
                  ) else { continue }
            do {
                do {
                    try await client.from("imported_runs")
                        .update(UpgradePayload(
                            resort_id: candidate.resort_id,
                            edge_id: candidate.edge_id,
                            difficulty: candidate.difficulty,
                            dataset_version: candidate.dataset_version,
                            matched_segment_ids: candidate.matched_segment_ids,
                            match_confidence: candidate.match_confidence,
                            match_method: candidate.match_method,
                            equipment_id_at_activity: candidate.equipment_id_at_activity,
                            raw_source_identity: candidate.raw_source_identity,
                            trail_name: candidate.trail_name
                        ))
                        .eq("profile_id", value: candidate.profile_id)
                        .eq("dedup_hash", value: candidate.dedup_hash)
                        .execute()
                } catch {
                    guard ImportedRunSchemaCompatibility.shouldRetryLegacy(after: error) else {
                        throw error
                    }
                    try await client.from("imported_runs")
                        .update(CoreUpgradePayload(
                            resort_id: candidate.resort_id,
                            edge_id: RecordedPaceEvidence.legacyEdgeID(
                                candidate.edge_id, method: candidate.match_method
                            ),
                            difficulty: candidate.difficulty,
                            trail_name: candidate.trail_name
                        ))
                        .eq("profile_id", value: candidate.profile_id)
                        .eq("dedup_hash", value: candidate.dedup_hash)
                        .execute()
                }
                upgraded.insert(candidate.dedup_hash)
            } catch {
                AppLog.importer.debug("duplicate-name upgrade skipped: \(error.localizedDescription)")
            }
        }
        return upgraded
    }
}
